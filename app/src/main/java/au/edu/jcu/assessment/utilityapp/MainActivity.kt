@Composable
fun UtilityApp(
    viewModel: WeatherViewModel = viewModel(factory = WeatherViewModel.Factory),
) {
    var selectedTab by remember { mutableStateOf("Utility") }

    val uiState by viewModel.uiState.collectAsState()
    val preferences by viewModel.preferences.collectAsState()

    Scaffold(
        bottomBar = {
            NavigationBar {
                NavigationBarItem(
                    icon = { Icon(Icons.Default.Home, contentDescription = "Utility") },
                    label = { Text("Utility") },
                    selected = selectedTab == "Utility",
                    onClick = { selectedTab = "Utility" },
                )
                NavigationBarItem(
                    icon = { Icon(Icons.Default.Settings, contentDescription = "Settings") },
                    label = { Text("Settings") },
                    selected = selectedTab == "Settings",
                    onClick = { selectedTab = "Settings" },
                )
            }
        },
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding),
        ) {
            when (selectedTab) {
                "Utility" -> UtilityScreen(
                    uiState = uiState,
                    onRefresh = { viewModel.loadWeather() },
                )

                "Settings" -> SettingsScreen(
                    preferences = preferences,
                    onSelectCity = { viewModel.selectCity(it) },
                    onSetTemperatureUnit = { viewModel.setTemperatureUnit(it) },
                    onSetWindSpeedUnit = { viewModel.setWindSpeedUnit(it) },
                    onToggleOutdoorAdvice = { viewModel.toggleOutdoorAdvice(it) },
                    onToggleApparentTemp = { viewModel.toggleApparentTemp(it) },
                    onToggleHumidity = { viewModel.toggleHumidity(it) },
                    onToggleWindSpeed = { viewModel.toggleWindSpeed(it) },
                )
            }
        }
    }
}
